// Writes conformance/index.json: what every conformance file holds (its sections, the number of cases in each, a sha256
// of the file). It is derived from the files on disk, so a case count is never typed into a document by hand: the docs
// point here and `--check` fails when the index is not what the files say. Run it after any exporter.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../conformance/", import.meta.url));
const out = `${dir}index.json`;

const files = {};
for (const name of readdirSync(dir).filter((f) => f.endsWith(".json") && f !== "index.json").sort()) {
  const bytes = readFileSync(`${dir}${name}`);
  const data = JSON.parse(bytes.toString("utf8"));
  // A section is a top-level list of cases; anything else at the top level (version, note, a constant) is not counted.
  const sections = Object.fromEntries(Object.entries(data).filter(([, v]) => Array.isArray(v)).map(([k, v]) => [k, v.length]));
  files[name] = {
    status: /\.v0\./.test(name) ? "draft" : "stable",
    sha256: createHash("sha256").update(bytes).digest("hex"),
    bytes: bytes.length,
    cases: Object.values(sections).reduce((a, b) => a + b, 0),
    sections,
  };
}
const text = `${JSON.stringify(
  {
    version: 1,
    note: "Generated by scripts/export-index.mjs from the files in this directory. A section is a top-level list of cases; `status` is draft for *.v0.json. Do not edit by hand: documents cite this file instead of repeating case counts.",
    files,
  },
  null,
  1,
)}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (current !== text) {
    console.error("conformance/index.json is not what the conformance files say; run `node scripts/export-index.mjs` and review the diff");
    process.exit(1);
  }
  console.log(`index.json matches ${Object.keys(files).length} conformance files`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${Object.keys(files).length} files)`);
}
